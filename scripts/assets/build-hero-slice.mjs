// Commercial District hero slice: compress what blender/hero_slice.py staged in .asset-cache/hero/ into
// public/assets/harbour/hero/ (meshopt geometry; the assets carry no textures: their material slots bind to the
// game's shared PBR library at load, see src/world/heroSlice.tsx) and write public/assets/harbour/hero/manifest.json
// (source, triangles, bytes, licence).
// Run: python blender/hero_slice.py   then   node scripts/assets/build-hero-slice.mjs
import fs from 'node:fs';
import path from 'node:path';
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { prune, dedup, weld, meshopt } from '@gltf-transform/functions';
import { MeshoptEncoder } from 'meshoptimizer';
import { CACHE, OUT, ensureDir, writeJSON, kb } from './common.mjs';

const STAGE = path.join(CACHE, 'hero'), DEST = ensureDir(path.join(OUT, 'harbour', 'hero'));
const io = () => new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.encoder': MeshoptEncoder });
const report = JSON.parse(fs.readFileSync(path.join(STAGE, 'report.json'), 'utf8'));
await MeshoptEncoder.ready;
const manifest = { note: 'Generated by scripts/assets/build-hero-slice.mjs from blender/hero_slice.py (source blender/source/hero_slice.blend).', assets: {} };
for (const key of Object.keys(report)) {
  const doc = await io().read(path.join(STAGE, `${key}.glb`)), root = doc.getRoot();
  // Weld only within a tolerance that keeps hard edges (the kit marks them with split normals).
  await doc.transform(dedup(), weld(), prune(), meshopt({ encoder: MeshoptEncoder, level: 'medium' }));
  const out = path.join(DEST, `${key}.glb`);
  await io().write(out, doc);
  let tris = 0; for (const m of root.listMeshes()) for (const p of m.listPrimitives()) tris += p.getIndices().getCount() / 3;
  console.log(`  ${key.padEnd(16)} ${tris} tris, ${root.listMaterials().length} material slots, ${kb(out)}`);
  manifest.assets[key] = { file: `harbour/hero/${key}.glb`, triangles: tris, bytes: fs.statSync(out).size, materials: report[key].materials,
    author: 'CampOS Worlds (original, modelled with blender/hero_slice.py)', license: 'Project-original; no third-party content' };
}
writeJSON(path.join(DEST, 'manifest.json'), manifest);
