// The Combat Arena's phone tier (public/assets/arena/mobile): the same environment surfaces, props and soldiers
// with 512² textures instead of 1024², made by dropping each texture's largest mip level (no re-encoding: what a
// phone draws is exactly the 512² mip it would have sampled from the full file anyway on a small screen). The Low
// graphics profile loads from here; first-person weapons and arms always stay full resolution.
// Usage: node scripts/assets/build-arena-mobile.mjs   (after build-arena.mjs; deterministic)
import fs from 'node:fs';
import path from 'node:path';
import { dropTopMips, shrinkGlb } from './ktx2-mips.mjs';

const ARENA = 'public/assets/arena', OUT = path.join(ARENA, 'mobile');
const jobs = [];
for (const key of fs.readdirSync(path.join(ARENA, 'textures'))) for (const f of fs.readdirSync(path.join(ARENA, 'textures', key))) jobs.push(`textures/${key}/${f}`);
for (const f of fs.readdirSync(path.join(ARENA, 'props'))) if (f.endsWith('.glb')) jobs.push(`props/${f}`);
for (const f of fs.readdirSync(path.join(ARENA, 'characters'))) if (/^soldier-.*\.(glb|ktx2)$/.test(f)) jobs.push(`characters/${f}`);
let before = 0, after = 0; const manifest = { note: 'Generated by scripts/assets/build-arena-mobile.mjs from the files one directory up.', files: {} };
for (const rel of jobs.sort()) {
  const src = fs.readFileSync(path.join(ARENA, rel)), out = rel.endsWith('.glb') ? shrinkGlb(src, 512) : dropTopMips(src, 512);
  fs.mkdirSync(path.dirname(path.join(OUT, rel)), { recursive: true }); fs.writeFileSync(path.join(OUT, rel), out);
  before += src.length; after += out.length; manifest.files[rel] = out.length;
}
manifest.bytes = after; manifest.fullBytes = before;
fs.writeFileSync(path.join(OUT, 'manifest.json'), JSON.stringify(manifest, null, 1));
console.log(`${jobs.length} files: ${(before / 1e6).toFixed(2)} MB -> ${(after / 1e6).toFixed(2)} MB (${Math.round(after / before * 100)}%)`);
