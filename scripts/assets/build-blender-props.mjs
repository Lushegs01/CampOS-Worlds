// Blender-authored Metropolis props: compress what blender/build.py staged in .asset-cache/blender/ into the arena
// pack, exactly like the Poly Haven props (Basis KTX2 textures, meshopt geometry), and record them in
// public/assets/arena/blender.json (source file, object, triangles, collision box, bytes, licence).
// Run: python blender/build.py   then   node scripts/assets/build-blender-props.mjs   then   node scripts/assets/build-arena-mobile.mjs
import fs from 'node:fs';
import path from 'node:path';
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS, KHRTextureBasisu } from '@gltf-transform/extensions';
import { prune, dedup, weld, meshopt } from '@gltf-transform/functions';
import { MeshoptEncoder } from 'meshoptimizer';
import { CACHE, OUT, ensureDir, encodeKTX2Batch, writeJSON, kb } from './common.mjs';

const STAGE = path.join(CACHE, 'blender'), ARENA = ensureDir(path.join(OUT, 'arena')), PROPS = ensureDir(path.join(ARENA, 'props'));
const io = () => new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.encoder': MeshoptEncoder });
const report = JSON.parse(fs.readFileSync(path.join(STAGE, 'report.json'), 'utf8'));
const only = process.argv.slice(2);
await MeshoptEncoder.ready;

const manifestFile = path.join(ARENA, 'blender.json');
const manifest = fs.existsSync(manifestFile) ? JSON.parse(fs.readFileSync(manifestFile, 'utf8')) : { props: {} };
for (const [key, info] of Object.entries(report)) {
  if (only.length && !only.includes(key)) continue;
  if (info.family === 'Weapons') continue; // weapon parts are merged into weapons (scripts/assets/add-weapon-part.mjs)
  const doc = await io().read(path.join(STAGE, `${key}.glb`)), root = doc.getRoot();
  await doc.transform(dedup(), weld(), prune());
  const kinds = new Map();
  for (const mat of root.listMaterials()) {
    if (mat.getBaseColorTexture()) kinds.set(mat.getBaseColorTexture(), 'color');
    if (mat.getNormalTexture()) kinds.set(mat.getNormalTexture(), 'normal');
    for (const t of [mat.getMetallicRoughnessTexture(), mat.getOcclusionTexture()]) if (t && !kinds.has(t)) kinds.set(t, 'linear');
  }
  const tmp = ensureDir(path.join(STAGE, 'ktx2')), jobs = [], list = root.listTextures();
  for (const [i, tex] of list.entries()) {
    const png = path.join(tmp, `${key}-${i}.png`), kind = kinds.get(tex) ?? 'linear';
    fs.writeFileSync(png, Buffer.from(tex.getImage()));
    jobs.push({ in: png, out: path.join(tmp, `${key}-${i}.ktx2`), kind, quality: kind === 'normal' ? 220 : 170, force: true });
  }
  await encodeKTX2Batch(jobs);
  doc.createExtension(KHRTextureBasisu).setRequired(true);
  for (const [i, tex] of list.entries()) tex.setImage(new Uint8Array(fs.readFileSync(path.join(tmp, `${key}-${i}.ktx2`)))).setMimeType('image/ktx2').setURI(`${key}-${i}.ktx2`);
  await doc.transform(prune(), meshopt({ encoder: MeshoptEncoder, level: 'medium' }));
  const out = path.join(PROPS, `${key}.glb`);
  await io().write(out, doc);
  let tris = 0; for (const m of root.listMeshes()) for (const p of m.listPrimitives()) tris += p.getIndices().getCount() / 3;
  console.log(`  ${key.padEnd(16)} ${tris} tris, ${list.length} textures, ${kb(out)}`);
  manifest.props[key] = {
    file: `props/${key}.glb`, source: info.blendSource, object: info.object, family: info.family, triangles: tris,
    collisionBox: info.collisionBox, textureSize: info.textureSize, bytes: fs.statSync(out).size,
    author: 'CampOS Worlds (original, modelled and baked with blender/build.py)', license: 'Project-original; no third-party content',
  };
}
manifest.note = 'Generated by scripts/assets/build-blender-props.mjs from .asset-cache/blender (python blender/build.py).';
writeJSON(manifestFile, manifest);
